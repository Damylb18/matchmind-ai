import { teamByApiName } from "../data/teams";
import type { Insight, MatchEvent } from "../types/match";
import {
  adaptInsight,
  type ExplanationAudience,
  type ExplanationLanguage,
  type StructuredExplanation,
} from "./explanation";

export type PersonalisedInsight = StructuredExplanation & {
  /** Values (e.g. the pressure average) were recomputed from the insight's own evidence events. */
  derivedFromEvidence: boolean;
  /** How many of the insight's evidence events this browser received. */
  evidenceReceived: number;
  evidenceTotal: number;
  /** Language of the displayed text: the selected one for templates; undefined (backend's own) for fallback. */
  contentLang: string | undefined;
};

/**
 * Supplies the structured values the templates read when the backend did not send them,
 * using only the insight's own evidence events received in this session. A value is
 * filled only when every cited evidence event is available, so it equals what the
 * backend rule computed. The original insight is never modified.
 */
export function withEvidenceData(insight: Insight, eventsById: ReadonlyMap<string, MatchEvent>) {
  const evidence = insight.evidence_event_ids
    .map((id) => eventsById.get(id))
    .filter((event): event is MatchEvent => event !== undefined);
  const data: Record<string, unknown> = { ...insight.data };
  let derived = false;

  const teamName = insight.team_id ? teamByApiName(insight.team_id)?.name : undefined;
  if (teamName && typeof data.team !== "string") data.team = teamName;

  if (insight.type === "pressure_surge" && typeof data.pressureAverage !== "number") {
    const values = evidence
      .map((event) => event.pressure)
      .filter((value): value is number => typeof value === "number");
    if (values.length > 0 && values.length === insight.evidence_event_ids.length) {
      data.pressureAverage = values.reduce((sum, value) => sum + value, 0) / values.length;
      data.pressureEventCount = values.length;
      derived = true;
    }
  }

  return { insight: { ...insight, data }, derived, received: evidence.length };
}

export function personalise(
  insight: Insight,
  audience: ExplanationAudience,
  language: ExplanationLanguage,
  eventsById: ReadonlyMap<string, MatchEvent>,
): PersonalisedInsight {
  const { insight: enriched, derived, received } = withEvidenceData(insight, eventsById);
  const adapted = adaptInsight(enriched, audience, language);
  return {
    ...adapted,
    contentLang: adapted.source === "local-demo-template" ? language : undefined,
    derivedFromEvidence: derived,
    evidenceReceived: received,
    evidenceTotal: insight.evidence_event_ids.length,
  };
}

/** Plain-language label for where the personalised text came from. Never claims AI generation. */
export const SOURCE_LABEL: Record<StructuredExplanation["source"], string> = {
  "local-demo-template": "Local template",
  "backend-fallback": "Backend text",
};

export const SOURCE_DESCRIPTION: Record<StructuredExplanation["source"], string> = {
  "local-demo-template":
    "Rewritten from a built-in local template for this audience and language. Not generated by Azure AI or any live language model.",
  "backend-fallback":
    "Original backend wording, shown unchanged because no local template exists for this insight type.",
};
