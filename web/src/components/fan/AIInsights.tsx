import { teamByApiName } from "../../data/teams";
import { usePersonaliser } from "../../hooks/usePersonaliser";
import { formatClockSeconds, matchTimeAgo } from "../../lib/format";
import type { InsightEntry } from "../../lib/matchState";
import { Icon } from "../icons/Icon";
import { InsightSource } from "../InsightSource";
import { EmptyState, Panel } from "../Panel";

type AIInsightsProps = {
  insights: InsightEntry[];
  clock: number | null;
  limit?: number;
  title?: string;
  variant?: "compact" | "editorial";
  onViewAll?: () => void;
};

const TYPE_LABELS: Record<string, string> = {
  pressure_surge: "Pressure surge",
  passing_pattern: "Passing pattern",
  shot_activity: "Shot activity",
};

export function AIInsights({
  insights,
  clock,
  limit = 4,
  title = "AI Insights",
  variant = "compact",
  onViewAll,
}: AIInsightsProps) {
  const personalise = usePersonaliser("fan");
  return (
    <Panel
      title={title}
      info="Detected by the backend rule engine (api/src/rules.ts), e.g. when a team's last 10 pressure events average above 0.75. Wording is adapted for fans from built-in local templates in the selected language — not generated by Azure AI."
      className={`insights-panel insights-${variant}`}
      actions={
        onViewAll && (
          <button type="button" className="link-button" onClick={onViewAll}>
            View all <Icon name="arrowRight" size={14} />
          </button>
        )
      }
    >
      {insights.length === 0 ? (
        <EmptyState>
          Watching the game. Insights appear when the backend detects a sustained pattern.
        </EmptyState>
      ) : (
        <ol className="insight-list">
          {insights.slice(0, limit).map((insight) => {
            const team = teamByApiName(insight.team);
            const text = personalise(insight);
            return (
              <li key={insight.key} className="insight">
                <span
                  className="insight-icon"
                  style={{ color: team?.colors.data, borderColor: team?.colors.data }}
                  aria-hidden="true"
                >
                  <Icon name={insight.type === "pressure_surge" ? "pressure" : "insight"} size={18} />
                </span>
                <div className="insight-body" lang={text.contentLang}>
                  <div className="insight-title-row">
                    <h3>{text.headline}</h3>
                    {clock !== null && (
                      <span className="insight-ago" title="Elapsed match time">
                        {matchTimeAgo(clock, insight.clock)}
                      </span>
                    )}
                  </div>
                  <p>{text.explanation}</p>
                  {/* Fallback text has no separate takeaway (the module repeats the explanation). */}
                  {variant === "editorial" && text.source === "local-demo-template" && (
                    <p className="insight-takeaway">{text.takeaway}</p>
                  )}
                  <p className="insight-meta">
                    <span>{formatClockSeconds(insight.clock)}</span>
                    <span>{team?.name ?? insight.team}</span>
                    <span>{TYPE_LABELS[insight.type] ?? insight.type}</span>
                    <span>{insight.evidence_event_ids.length} evidence events</span>
                    <InsightSource personalised={text} />
                  </p>
                </div>
              </li>
            );
          })}
        </ol>
      )}
    </Panel>
  );
}
